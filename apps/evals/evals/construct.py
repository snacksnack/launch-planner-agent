"""Construct validity: can the judge detect degradation we planted ourselves?

Human agreement is the stronger validation and the one RC1-250 asks for. It also
depends on someone carefully making 144 judgements, and three attempts at this
set produced labels the labeller told us not to trust — twice scoring the
rule-written `fallback` variant *lower* on groundedness than the deliberately
degraded one, which is the inverse of the construct.

So this is the check that does not need a human at all.

`fallback` is generated by `planner_core.fallback_narrative`, a template over the
facts: it restates them and can contain no unsupported claim. `degraded` is
generated from a prompt written to invite exactly what the rubric penalises.
Whether a judge ranks the first above the second is a fact about the judge, and
nobody has to score anything for it to be true.

**This is weaker than human agreement and does not substitute for it.** A judge
can detect a planted extreme and still disagree with a careful human all over the
subtle middle — the range where real regressions live. So passing this earns a
dimension nothing: it does not clear the gating floor, and `docs/judging.md`
says so. What it earns is the ability to say the judge is measuring *something*
real rather than emitting noise, which is more than an uncalibrated judge can
claim.

The same instinct as planted-defect recall in RC1-253: "did it find the thing we
hid" beats any rubric score, because the answer does not depend on whose
judgement you trust.
"""

from __future__ import annotations

from dataclasses import dataclass

from evals.rubric import DIMENSION_KEYS, Score

#: Grounded by construction, and degraded by construction. The pair the check
#: is built on — the two variants whose relative ranking is known before anyone
#: scores anything.
CLEAN = "fallback"
PLANTED = "degraded"

#: **Only the dimensions the planted degradation actually attacks.**
#:
#: `DEGRADED_SYSTEM_PROMPT` asks for reassurance, diplomacy, causal context and
#: team sentiment, and says expansiveness is fine. That manufactures unsupported
#: claims (groundedness) and the wrong register for an executive update (tone).
#: It does **not** attack completeness — an expansive narrative covers *more* of
#: the facts, not less — and its effect on actionability is ambiguous.
#:
#: Running the check on an untargeted dimension produces a number that looks
#: like a judge failure and is really a statement about the prompt. Measured:
#: completeness came back at 33%, below chance, because the planted outputs are
#: genuinely the more complete ones. That is the check being wrong, not the
#: judge — so those dimensions are reported as out of scope rather than scored.
TARGETED: frozenset[str] = frozenset({"groundedness", "tone"})

#: Below this, the judge is not reliably separating planted degradation. Not a
#: gating threshold — nothing here gates. It is the line under which the judge
#: cannot be said to be measuring the construct at all.
SEPARATION_FLOOR = 0.7


@dataclass(frozen=True)
class Separation:
    """How well one dimension's scores separate clean outputs from planted ones."""

    dimension: str
    targeted: bool
    clean_mean: float
    planted_mean: float
    pairs: int
    correct: int
    ties: int

    @property
    def rate(self) -> float:
        """Fraction of clean-vs-planted pairs ranked correctly, ties counting half.

        A rank statistic rather than a mean difference: it is unaffected by the
        judge being uniformly harsh or generous, which is exactly the kind of
        offset a mean would confuse with a real signal.
        """
        if not self.pairs:
            return 0.0
        return (self.correct + self.ties / 2) / self.pairs

    @property
    def detects(self) -> bool:
        """Only meaningful where the degradation targets the dimension."""
        return self.targeted and self.rate >= SEPARATION_FLOOR

    @property
    def headline(self) -> str:
        return f"{self.rate:.0%}"


def separation(
    labels: dict[str, dict[str, Score]],
    variants: dict[str, str],
) -> list[Separation]:
    """Per dimension, how often a clean output outranks a planted one.

    Every clean seed is compared against every planted seed — all pairs, not
    matched ones, because the two variants are generated from the same facts and
    a pairwise comparison over the whole set is both simpler and less sensitive
    to any single fact set being unusual.
    """
    results = []
    for dimension in DIMENSION_KEYS:
        clean = [
            int(scores[dimension])
            for seed_id, scores in labels.items()
            if variants.get(seed_id) == CLEAN and dimension in scores
        ]
        planted = [
            int(scores[dimension])
            for seed_id, scores in labels.items()
            if variants.get(seed_id) == PLANTED and dimension in scores
        ]
        correct = sum(1 for c in clean for p in planted if c > p)
        ties = sum(1 for c in clean for p in planted if c == p)
        results.append(
            Separation(
                dimension=dimension,
                targeted=dimension in TARGETED,
                clean_mean=sum(clean) / len(clean) if clean else 0.0,
                planted_mean=sum(planted) / len(planted) if planted else 0.0,
                pairs=len(clean) * len(planted),
                correct=correct,
                ties=ties,
            )
        )
    return results
